  const storageKey = 'mira-vellani-language';
  function applyLanguage(requested) {
    const language = Object.hasOwn(locales, requested) ? requested : 'en';
    const locale = locales[language];
    const message = key => locale.messages[key] ?? locales.en.messages[key];
    document.documentElement.lang = language;
    document.documentElement.dir = locale.dir;
    document.title = message('pageTitle');
    document.querySelectorAll('[data-i18n]').forEach(element => {
      // Only trusted, repository-owned translations contain markup.
      element.innerHTML = message(element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(element => {
      const [attribute, key] = element.dataset.i18nAttr.split(':');
      element.setAttribute(attribute, message(key));
    });
    document.querySelectorAll('[data-player-title]').forEach(element => {
      element.setAttribute('title', message('playerTitle') + ': ' + element.dataset.playerTitle);
    });
    document.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    return language;
  }
